-- STAGING ONLY. Do not move into supabase/migrations until issue #342 staging gates pass.
-- Immutable TR/EN dictionary releases with deterministic SHA-256, active pointers and rollback audit.
-- Existing runtime keeps current behavior until an active release exists for a language.

create table if not exists public.dictionary_releases_v1 (
  release_id uuid primary key default gen_random_uuid(),
  release_key text not null unique,
  language text not null check (language in ('tr','en')),
  checksum_sha256 text not null check (checksum_sha256 ~ '^[0-9a-f]{64}$'),
  word_count integer not null check (word_count > 0),
  words text[] not null,
  source_manifest jsonb not null,
  created_at timestamptz not null default now(),
  created_by uuid,
  constraint dictionary_release_words_count_check check (cardinality(words)=word_count),
  constraint dictionary_release_language_checksum_unique unique(language,checksum_sha256)
);

create table if not exists public.dictionary_release_state_v1 (
  language text primary key check (language in ('tr','en')),
  active_release_id uuid not null references public.dictionary_releases_v1(release_id) on delete restrict,
  activated_at timestamptz not null default now(),
  activated_by uuid
);

create table if not exists public.dictionary_release_events_v1 (
  id bigint generated by default as identity primary key,
  language text not null check (language in ('tr','en')),
  action text not null check (action in ('create','activate','rollback')),
  release_id uuid not null references public.dictionary_releases_v1(release_id) on delete restrict,
  previous_release_id uuid references public.dictionary_releases_v1(release_id) on delete restrict,
  actor_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.dictionary_releases_v1 enable row level security;
alter table public.dictionary_release_state_v1 enable row level security;
alter table public.dictionary_release_events_v1 enable row level security;

