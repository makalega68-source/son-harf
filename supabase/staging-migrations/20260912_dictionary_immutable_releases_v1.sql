on public.dictionary_releases_v1
for select
to authenticated
using (
  exists (
    select 1
    from public.dictionary_release_state_v1 s
    where s.language=dictionary_releases_v1.language
      and s.active_release_id=dictionary_releases_v1.release_id
  )
);

