create or replace function public.finish_word_arena_internal_v1(p_room_id uuid)
returns public.word_arena_rooms
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  r public.word_arena_rooms;
  v_uid uuid:=auth.uid();
  v_host_score int:=0;
  v_guest_score int:=0;
  v_host_words int:=0;
  v_guest_words int:=0;
  v_winner uuid;
  v_host_reward int:=0;
  v_guest_reward int:=0;
  v_tid uuid;
  v_finished timestamptz;
begin
  if v_uid is null then raise exception 'unauthorized'; end if;

  select * into r
  from public.word_arena_rooms
  where id=p_room_id
  for update;

  if r.id is null then raise exception 'arena_room_not_found'; end if;
  if v_uid not in (r.host_id,r.guest_id) then raise exception 'arena_not_participant'; end if;
  if r.status='finished' then return r; end if;
  if r.status<>'playing' then raise exception 'arena_not_active'; end if;
  if now()<r.ends_at then raise exception 'arena_not_finished_yet'; end if;

  select coalesce(sum(
    w.base_points +
    case when not exists(
      select 1 from public.word_arena_words o
      where o.room_id=w.room_id
        and o.user_id=r.guest_id
        and o.normalized_word=w.normalized_word
    ) then w.base_points else 0 end
  ),0)::int,
  count(*)::int
  into v_host_score,v_host_words
  from public.word_arena_words w
  where w.room_id=r.id and w.user_id=r.host_id;

  select coalesce(sum(
    w.base_points +
    case when not exists(
      select 1 from public.word_arena_words o
      where o.room_id=w.room_id
        and o.user_id=r.host_id
        and o.normalized_word=w.normalized_word
    ) then w.base_points else 0 end
  ),0)::int,
  count(*)::int
  into v_guest_score,v_guest_words
  from public.word_arena_words w
  where w.room_id=r.id and w.user_id=r.guest_id;

  v_winner:=case
    when v_host_score>v_guest_score then r.host_id
    when v_guest_score>v_host_score then r.guest_id
    else null
  end;

  if not r.result_applied then
    update public.profiles
    set total_matches=total_matches+1,
        wins=wins+case when v_winner=id then 1 else 0 end,
        losses=losses+case when v_winner is not null and v_winner<>id then 1 else 0 end,
        valid_words=valid_words+case when id=r.host_id then v_host_words else v_guest_words end,
        rating=greatest(
          100,
          rating+case
            when v_winner is null then 0
            when v_winner=id then 18
            else -12
          end
        ),
        presence_status='online',
        last_seen_at=now()
    where id in (r.host_id,r.guest_id);

    v_host_reward:=case
      when v_winner is null then 7
      when v_winner=r.host_id then 12
      else 5
    end;
    v_guest_reward:=case
      when v_winner is null then 7
      when v_winner=r.guest_id then 12
      else 5
    end;

    update public.profiles
    set diamonds=diamonds+case when id=r.host_id then v_host_reward else v_guest_reward end
    where id in (r.host_id,r.guest_id);

    insert into public.diamond_ledger(user_id,delta,reason,item_id)
    values
      (r.host_id,v_host_reward,'word_arena_match:'||r.id::text,null),
      (r.guest_id,v_guest_reward,'word_arena_match:'||r.id::text,null);

    v_finished:=coalesce(r.ends_at,now());

    insert into public.club_point_events(club_id,user_id,room_id,arena_room_id,points,created_at)
    select cm.club_id,r.host_id,null,r.id,
           case when v_winner is null then 5 when v_winner=r.host_id then 10 else 3 end,
           v_finished
    from public.club_members cm
    where cm.user_id=r.host_id
    on conflict do nothing;

    insert into public.club_point_events(club_id,user_id,room_id,arena_room_id,points,created_at)
    select cm.club_id,r.guest_id,null,r.id,
           case when v_winner is null then 5 when v_winner=r.guest_id then 10 else 3 end,
           v_finished
    from public.club_members cm
    where cm.user_id=r.guest_id
    on conflict do nothing;

    select t.id into v_tid
    from public.weekly_tournaments t
    where v_finished>=t.starts_at and v_finished<t.ends_at
    order by t.starts_at desc
    limit 1;

    if v_tid is not null then
      insert into public.weekly_tournament_match_events(
        tournament_id,user_id,room_id,arena_room_id,points,won,created_at
      )
      select v_tid,r.host_id,null,r.id,
             case when v_winner is null then 2 when v_winner=r.host_id then 3 else 1 end,
             v_winner=r.host_id,
             v_finished
      where exists(
        select 1 from public.weekly_tournament_entries e
        where e.tournament_id=v_tid
          and e.user_id=r.host_id
          and e.joined_at<=r.starts_at
      )
      on conflict do nothing;

      insert into public.weekly_tournament_match_events(
        tournament_id,user_id,room_id,arena_room_id,points,won,created_at
      )
      select v_tid,r.guest_id,null,r.id,
             case when v_winner is null then 2 when v_winner=r.guest_id then 3 else 1 end,
             v_winner=r.guest_id,
             v_finished
      where exists(
        select 1 from public.weekly_tournament_entries e
        where e.tournament_id=v_tid
          and e.user_id=r.guest_id
          and e.joined_at<=r.starts_at
      )
      on conflict do nothing;
    end if;
  end if;

  update public.word_arena_rooms
  set status='finished',
      host_score=v_host_score,
      guest_score=v_guest_score,
      winner_id=v_winner,
      result_applied=true,
      finished_at=now()
  where id=r.id
  returning * into r;

  update public.word_arena_queue
  set status='cancelled',heartbeat_at=now()
  where user_id in (r.host_id,r.guest_id);

  return r;
end
$;

create or replace function public.join_word_arena_v1(p_language text default 'tr')
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
  v_lang text:=case when lower(trim(coalesce(p_language,'tr')))='en' then 'en' else 'tr' end;
  v_opponent uuid;
  v_room public.word_arena_rooms;
  v_existing public.word_arena_rooms;
  v_my_rating int;
begin
  if v_uid is null then raise exception 'unauthorized'; end if;

  perform pg_advisory_xact_lock(88220011);

  select * into v_existing
  from public.word_arena_rooms
  where status='playing'
    and (host_id=v_uid or guest_id=v_uid)
  order by created_at desc
  limit 1;

  if v_existing.id is not null then
    if now()>=v_existing.ends_at then
      v_existing:=public.finish_word_arena_internal_v1(v_existing.id);
    else
      return jsonb_build_object('status','matched','room_id',v_existing.id);
    end if;
  end if;

  if exists(
    select 1 from public.game_rooms
    where status in ('playing','quiz','final','sudden_death')
      and (host_id=v_uid or guest_id=v_uid)
  ) then
    raise exception 'player_already_in_game';
  end if;

  update public.word_arena_queue
  set status='cancelled'
  where status='waiting'
    and heartbeat_at<now()-interval '90 seconds';

  select coalesce(rating,1000) into v_my_rating
  from public.profiles where id=v_uid;

  select q.user_id into v_opponent
  from public.word_arena_queue q
  join public.profiles p on p.id=q.user_id
  where q.status='waiting'
    and q.language=v_lang
    and q.user_id<>v_uid
    and q.heartbeat_at>=now()-interval '90 seconds'
    and not exists(
      select 1 from public.user_blocks b
      where (b.blocker_id=v_uid and b.blocked_id=q.user_id)
         or (b.blocker_id=q.user_id and b.blocked_id=v_uid)
    )
    and not exists(
      select 1 from public.word_arena_rooms ar
      where ar.status='playing'
        and (ar.host_id=q.user_id or ar.guest_id=q.user_id)
    )
    and not exists(
      select 1 from public.game_rooms gr
      where gr.status in ('playing','quiz','final','sudden_death')
        and (gr.host_id=q.user_id or gr.guest_id=q.user_id)
    )
  order by abs(coalesce(p.rating,1000)-v_my_rating),q.queued_at
  for update of q skip locked
  limit 1;

  if v_opponent is null then
    insert into public.word_arena_queue(user_id,language,status,room_id,queued_at,heartbeat_at)
    values(v_uid,v_lang,'waiting',null,now(),now())
    on conflict(user_id) do update set
      language=excluded.language,
      status='waiting',
      room_id=null,
      queued_at=case
        when public.word_arena_queue.status='waiting'
         and public.word_arena_queue.language=excluded.language
        then public.word_arena_queue.queued_at
        else now()
      end,
      heartbeat_at=now();

    update public.profiles set presence_status='online',last_seen_at=now() where id=v_uid;
    return jsonb_build_object('status','waiting');
  end if;

  insert into public.word_arena_rooms(
    host_id,guest_id,language,letters,status,starts_at,ends_at
  )
  values(
    v_opponent,
    v_uid,
    v_lang,
    public.word_arena_letter_set_v1(v_lang),
    'playing',
    now()+interval '3 seconds',
    now()+interval '63 seconds'
  )
  returning * into v_room;

  update public.word_arena_queue
  set status='matched',room_id=v_room.id,heartbeat_at=now()
  where user_id=v_opponent;

  insert into public.word_arena_queue(user_id,language,status,room_id,queued_at,heartbeat_at)
  values(v_uid,v_lang,'matched',v_room.id,now(),now())
  on conflict(user_id) do update set
    language=excluded.language,
    status='matched',
    room_id=excluded.room_id,
    queued_at=now(),
    heartbeat_at=now();

  update public.profiles
  set presence_status='in_game',last_seen_at=now()
  where id in (v_uid,v_opponent);

  return jsonb_build_object('status','matched','room_id',v_room.id);
end
$;

create or replace function public.poll_word_arena_v1()
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
  q public.word_arena_queue;
  r public.word_arena_rooms;
begin
  if v_uid is null then raise exception 'unauthorized'; end if;

  select * into q from public.word_arena_queue where user_id=v_uid;
  if q.user_id is null then return jsonb_build_object('status','idle'); end if;

  if q.status='waiting' then
    update public.word_arena_queue set heartbeat_at=now() where user_id=v_uid;
    return jsonb_build_object('status','waiting');
  end if;

  if q.room_id is not null then
    select * into r from public.word_arena_rooms where id=q.room_id;
    if r.id is not null and r.status='playing' and now()>=r.ends_at then
      r:=public.finish_word_arena_internal_v1(r.id);
    end if;
    return jsonb_build_object(
      'status',case when r.status='finished' then 'finished' else 'matched' end,
      'room_id',q.room_id
    );
  end if;

  return jsonb_build_object('status',q.status);
end
$;

