create or replace function public.submit_word_arena_v1(p_room_id uuid,p_word text)
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
  r public.word_arena_rooms;
  v_norm text;
  v_len int;
  v_combo int:=1;
  v_prev public.word_arena_words;
  v_points int;
  v_score int;
  v_word text:=trim(coalesce(p_word,''));
begin
  if v_uid is null then raise exception 'unauthorized'; end if;

  select * into r
  from public.word_arena_rooms
  where id=p_room_id
  for update;

  if r.id is null then raise exception 'arena_room_not_found'; end if;
  if v_uid not in (r.host_id,r.guest_id) then raise exception 'arena_not_participant'; end if;
  if r.status<>'playing' then return jsonb_build_object('accepted',false,'status',r.status); end if;

  if now()>=r.ends_at then
    r:=public.finish_word_arena_internal_v1(r.id);
    return jsonb_build_object('accepted',false,'status','finished');
  end if;

  if now()<r.starts_at then raise exception 'arena_not_started'; end if;

  v_norm:=public.normalize_game_word(r.language,v_word);
  v_len:=char_length(v_norm);

  if v_len<3 or v_len>10 then raise exception 'arena_word_length'; end if;
  if not public.arena_word_fits_letters_v1(v_norm,r.letters) then raise exception 'arena_letters_mismatch'; end if;

  if not exists(
    select 1 from public.dictionary_words d
    where d.language=r.language
      and d.active
      and d.normalized_word=v_norm
  ) then
    raise exception 'arena_invalid_word';
  end if;

  if exists(
    select 1 from public.word_arena_words w
    where w.room_id=r.id and w.user_id=v_uid and w.normalized_word=v_norm
  ) then
    raise exception 'arena_duplicate_word';
  end if;

  select * into v_prev
  from public.word_arena_words
  where room_id=r.id and user_id=v_uid
  order by created_at desc,id desc
  limit 1;

  if v_prev.id is not null and now()-v_prev.created_at<=interval '8 seconds' then
    v_combo:=least(v_prev.combo+1,99);
  end if;

  v_points:=
    v_len
    +greatest(0,v_len-4)*2
    +least(greatest(v_combo-1,0),4);

  insert into public.word_arena_words(
    room_id,user_id,word,normalized_word,base_points,combo
  )
  values(r.id,v_uid,v_word,v_norm,v_points,v_combo);

  select coalesce(sum(base_points),0)::int into v_score
  from public.word_arena_words
  where room_id=r.id and user_id=v_uid;

  update public.word_arena_rooms
  set host_score=case when v_uid=host_id then v_score else host_score end,
      guest_score=case when v_uid=guest_id then v_score else guest_score end
  where id=r.id;

  return jsonb_build_object(
    'accepted',true,
    'status','playing',
