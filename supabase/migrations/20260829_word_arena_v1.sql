returns trigger
language plpgsql
set search_path=public,pg_temp
as $$
begin
  if new.status='waiting' and exists(
    select 1 from public.word_arena_rooms r
    where r.status='playing'
      and (r.host_id=new.user_id or r.guest_id=new.user_id)
      and r.ends_at>now()
  ) then
    raise exception 'word_arena_match_active';
  end if;
  return new;
end
$;

