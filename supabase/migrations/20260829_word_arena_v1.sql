-- Word Arena v1: simultaneous 60-second word duel.
-- Same letters for both players, unique words score 2x at finalization.
-- Competitive entry remains free and all rewards are earned.

create or replace function public.arena_word_fits_letters_v1(p_word text,p_letters text)
returns boolean
language sql
immutable
set search_path=public,pg_temp
as $$
  with wc as (
    select ch,count(*)::int n
    from regexp_split_to_table(coalesce(p_word,''),'') ch
    where ch<>''
    group by ch
  ),
  lc as (
    select ch,count(*)::int n
    from regexp_split_to_table(coalesce(p_letters,''),'') ch
    where ch<>''
    group by ch
  )
  select coalesce(bool_and(wc.n<=coalesce(lc.n,0)),true)
  from wc left join lc using(ch)
$;

revoke all on function public.arena_word_fits_letters_v1(text,text) from public,anon,authenticated;

