$$;

create table if not exists public.clubs (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  tag text not null,
  description text not null default '',
  owner_id uuid not null references public.profiles(id) on delete restrict,
  max_members integer not null default 30 check (max_members between 2 and 30),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (char_length(btrim(name)) between 3 and 24),
  check (char_length(btrim(tag)) between 2 and 6),
  check (char_length(description) <= 180)
);
create unique index if not exists clubs_name_lower_uq on public.clubs(lower(btrim(name)));
create unique index if not exists clubs_tag_upper_uq on public.clubs(upper(btrim(tag)));
create index if not exists clubs_owner_idx on public.clubs(owner_id);

create table if not exists public.club_members (
  club_id uuid not null references public.clubs(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','moderator','member')),
  joined_at timestamptz not null default now(),
  primary key (club_id,user_id),
  unique (user_id)
);
create index if not exists club_members_club_joined_idx on public.club_members(club_id,joined_at);

create table if not exists public.club_messages (
  id uuid primary key default gen_random_uuid(),
  club_id uuid not null references public.clubs(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 300),
  created_at timestamptz not null default now()
);
create index if not exists club_messages_club_created_idx on public.club_messages(club_id,created_at desc);

create table if not exists public.club_point_events (
  id bigint generated by default as identity primary key,
  club_id uuid not null references public.clubs(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  room_id uuid not null references public.game_rooms(id) on delete cascade,
  points integer not null check (points between 0 and 50),
  created_at timestamptz not null default now(),
  unique (room_id,user_id)
);
create index if not exists club_point_events_club_created_idx on public.club_point_events(club_id,created_at desc);

create table if not exists public.weekly_tournaments (
  id uuid primary key default gen_random_uuid(),
  week_start date not null unique,
  name text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

create table if not exists public.weekly_tournament_entries (
  tournament_id uuid not null references public.weekly_tournaments(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key(tournament_id,user_id)
);
create index if not exists weekly_tournament_entries_joined_idx on public.weekly_tournament_entries(tournament_id,joined_at);

create table if not exists public.weekly_tournament_match_events (
  id bigint generated by default as identity primary key,
  tournament_id uuid not null references public.weekly_tournaments(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  room_id uuid not null references public.game_rooms(id) on delete cascade,
  points integer not null check(points between 0 and 10),
  won boolean not null default false,
  created_at timestamptz not null default now(),
  unique(tournament_id,room_id,user_id)
);
create index if not exists weekly_tournament_events_rank_idx
  on public.weekly_tournament_match_events(tournament_id,user_id,created_at);

create table if not exists public.weekly_tournament_reward_claims (
  tournament_id uuid not null references public.weekly_tournaments(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  final_rank integer not null,
  reward_coins integer not null check(reward_coins >= 0),
  claimed_at timestamptz not null default now(),
  primary key(tournament_id,user_id)
);

