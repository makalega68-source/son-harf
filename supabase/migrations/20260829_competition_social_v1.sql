create or replace function public.league_for_rating_v1(p_rating integer)
returns text
language sql
immutable
set search_path=public,pg_temp
as $$
  select case
    when coalesce(p_rating,1000) >= 1800 then 'EFSANE'
    when coalesce(p_rating,1000) >= 1600 then 'ELMAS'
    when coalesce(p_rating,1000) >= 1400 then 'PLATİN'
    when coalesce(p_rating,1000) >= 1250 then 'ALTIN'
    when coalesce(p_rating,1000) >= 1100 then 'GÜMÜŞ'
