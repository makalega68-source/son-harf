create or replace function public.get_weekly_tournament_v1()
returns table(
  tournament_id uuid,name text,week_start date,starts_at timestamptz,ends_at timestamptz,
  joined boolean,my_points bigint,my_wins bigint,my_losses bigint,my_rank bigint,player_count bigint
)
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare v_tid uuid;
begin
  if auth.uid() is null then raise exception 'unauthorized'; end if;
  v_tid:=public.ensure_weekly_tournament_v1();

  return query
  with score as (
    select e.user_id,coalesce(sum(m.points),0)::bigint pts,
           count(*) filter(where m.won)::bigint wins,
           count(*) filter(where not m.won)::bigint losses
    from public.weekly_tournament_entries e
    left join public.weekly_tournament_match_events m
      on m.tournament_id=e.tournament_id and m.user_id=e.user_id
    where e.tournament_id=v_tid
    group by e.user_id
  ),
  ranked as (
    select s.*,dense_rank() over(order by s.pts desc,s.wins desc,s.user_id)::bigint rnk from score s
  )
  select t.id,t.name,t.week_start,t.starts_at,t.ends_at,
         exists(select 1 from public.weekly_tournament_entries e where e.tournament_id=t.id and e.user_id=auth.uid()),
         coalesce((select r.pts from ranked r where r.user_id=auth.uid()),0)::bigint,
         coalesce((select r.wins from ranked r where r.user_id=auth.uid()),0)::bigint,
         coalesce((select r.losses from ranked r where r.user_id=auth.uid()),0)::bigint,
         coalesce((select r.rnk from ranked r where r.user_id=auth.uid()),0)::bigint,
         (select count(*)::bigint from public.weekly_tournament_entries e where e.tournament_id=t.id)
  from public.weekly_tournaments t
  where t.id=v_tid;
end $$;

