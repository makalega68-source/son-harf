create or replace function public.create_club_v1(p_name text,p_tag text,p_description text default '')
returns uuid
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
  v_name text:=btrim(coalesce(p_name,''));
  v_tag text:=upper(btrim(coalesce(p_tag,'')));
  v_description text:=btrim(coalesce(p_description,''));
  v_club uuid;
begin
  if v_uid is null then raise exception 'unauthorized'; end if;
  if char_length(v_name) not between 3 and 24 then raise exception 'invalid_club_name'; end if;
  if char_length(v_tag) not between 2 and 6 or v_tag !~ '^[A-Z0-9ÇĞİÖŞÜ]+$' then raise exception 'invalid_club_tag'; end if;
  if char_length(v_description)>180 then raise exception 'description_too_long'; end if;
  if exists(select 1 from public.club_members where user_id=v_uid) then raise exception 'already_in_club'; end if;

  insert into public.clubs(name,tag,description,owner_id)
  values(v_name,v_tag,v_description,v_uid)
  returning id into v_club;

  insert into public.club_members(club_id,user_id,role)
  values(v_club,v_uid,'owner');

  return v_club;
exception when unique_violation then
  raise exception 'club_name_or_tag_taken';
end $$;

create or replace function public.join_club_v1(p_club_id uuid)
returns uuid
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
  v_max int;
  v_count int;
begin
  if v_uid is null then raise exception 'unauthorized'; end if;
  if exists(select 1 from public.club_members where user_id=v_uid) then raise exception 'already_in_club'; end if;

  select max_members into v_max from public.clubs where id=p_club_id for update;
  if v_max is null then raise exception 'club_not_found'; end if;

  select count(*)::int into v_count from public.club_members where club_id=p_club_id;
  if v_count>=v_max then raise exception 'club_full'; end if;

  insert into public.club_members(club_id,user_id,role)
  values(p_club_id,v_uid,'member');
  return p_club_id;
end $$;

create or replace function public.leave_club_v1()
returns void
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
  v_club uuid;
  v_role text;
  v_count int;
begin
  if v_uid is null then raise exception 'unauthorized'; end if;
  select club_id,role into v_club,v_role from public.club_members where user_id=v_uid;
  if v_club is null then raise exception 'not_in_club'; end if;

  select count(*)::int into v_count from public.club_members where club_id=v_club;
  if v_role='owner' and v_count>1 then raise exception 'transfer_owner_before_leaving'; end if;

  if v_role='owner' then
    delete from public.clubs where id=v_club;
  else
    delete from public.club_members where club_id=v_club and user_id=v_uid;
  end if;
end $$;

create or replace function public.transfer_club_owner_v1(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
  v_club uuid;
begin
  if v_uid is null then raise exception 'unauthorized'; end if;
  select club_id into v_club from public.club_members where user_id=v_uid and role='owner';
  if v_club is null then raise exception 'owner_required'; end if;
  if p_user_id=v_uid then return; end if;
  if not exists(select 1 from public.club_members where club_id=v_club and user_id=p_user_id) then
    raise exception 'target_not_member';
  end if;

  update public.club_members set role='member' where club_id=v_club and user_id=v_uid;
  update public.club_members set role='owner' where club_id=v_club and user_id=p_user_id;
  update public.clubs set owner_id=p_user_id,updated_at=now() where id=v_club;
end $$;

create or replace function public.get_club_directory_v1(p_limit integer default 30)
returns table(
  club_id uuid,name text,tag text,description text,member_count integer,max_members integer,
  weekly_points bigint,owner_name text
)
language sql
stable
security definer
set search_path=public,pg_temp
as $$
with week_boundary as (
  select (date_trunc('week', timezone('Europe/Istanbul',now())) at time zone 'Europe/Istanbul') as week_start
),
member_counts as (
  select club_id,count(*)::int member_count from public.club_members group by club_id
),
points as (
  select e.club_id,sum(e.points)::bigint weekly_points
  from public.club_point_events e, week_boundary w
  where e.created_at>=w.week_start
  group by e.club_id
)
select c.id,c.name,c.tag,c.description,coalesce(mc.member_count,0),c.max_members,
       coalesce(p.weekly_points,0),o.display_name
from public.clubs c
join public.profiles o on o.id=c.owner_id
left join member_counts mc on mc.club_id=c.id
left join points p on p.club_id=c.id
order by coalesce(p.weekly_points,0) desc,coalesce(mc.member_count,0) desc,lower(c.name)
limit greatest(1,least(coalesce(p_limit,30),100))
$$;

create or replace function public.get_my_club_v1()
returns table(
  club_id uuid,name text,tag text,description text,role text,member_count integer,
  max_members integer,weekly_points bigint,weekly_rank bigint
)
language sql
stable
security definer
set search_path=public,pg_temp
as $$
with me as (
  select cm.club_id,cm.role from public.club_members cm where cm.user_id=auth.uid()
),
week_boundary as (
  select (date_trunc('week', timezone('Europe/Istanbul',now())) at time zone 'Europe/Istanbul') as week_start
),
scores as (
  select c.id as club_id,
         coalesce(sum(e.points) filter(where e.created_at>=w.week_start),0)::bigint as pts
  from public.clubs c
  cross join week_boundary w
  left join public.club_point_events e on e.club_id=c.id
  group by c.id
),
ranked as (
  select club_id,pts,dense_rank() over(order by pts desc,club_id)::bigint as rnk from scores
)
select c.id,c.name,c.tag,c.description,m.role,
       (select count(*)::int from public.club_members x where x.club_id=c.id),
       c.max_members,r.pts,r.rnk
from me m
join public.clubs c on c.id=m.club_id
join ranked r on r.club_id=c.id
$$;

