create or replace function public.claim_previous_weekly_tournament_reward_v1()
returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
  v_tid uuid;
  v_rank int;
  v_reward int;
  v_balance int;
begin
  if v_uid is null then raise exception 'unauthorized'; end if;

  select t.id into v_tid
  from public.weekly_tournaments t
  where t.ends_at<=now()
    and exists(select 1 from public.weekly_tournament_entries e where e.tournament_id=t.id and e.user_id=v_uid)
  order by t.ends_at desc
  limit 1;

  if v_tid is null then raise exception 'no_completed_tournament'; end if;
  if exists(select 1 from public.weekly_tournament_reward_claims c where c.tournament_id=v_tid and c.user_id=v_uid) then
    raise exception 'reward_already_claimed';
  end if;

  with score as (
    select e.user_id,coalesce(sum(m.points),0)::bigint pts,count(*) filter(where m.won)::bigint wins
    from public.weekly_tournament_entries e
    left join public.weekly_tournament_match_events m
      on m.tournament_id=e.tournament_id and m.user_id=e.user_id
    where e.tournament_id=v_tid
    group by e.user_id
  ),
  ranked as (
    select s.user_id,dense_rank() over(order by s.pts desc,s.wins desc,s.user_id)::int rnk from score s
  )
  select rnk into v_rank from ranked where user_id=v_uid;

  v_reward:=case
    when v_rank=1 then 1000
    when v_rank=2 then 600
    when v_rank=3 then 400
    when v_rank between 4 and 10 then 150
    else 50
  end;

  insert into public.weekly_tournament_reward_claims(tournament_id,user_id,final_rank,reward_coins)
  values(v_tid,v_uid,v_rank,v_reward);

  update public.profiles set diamonds=coalesce(diamonds,0)+v_reward
  where id=v_uid returning diamonds into v_balance;

  insert into public.diamond_ledger(user_id,delta,reason)
  values(v_uid,v_reward,'weekly_tournament_reward');

  return jsonb_build_object('success',true,'rank',v_rank,'reward_coins',v_reward,'balance',v_balance);
end $$;

create or replace function public.award_competition_points_v1()
returns trigger
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_tid uuid;
  v_finished timestamptz:=coalesce(new.finished_at,now());
begin
  if not (new.stats_applied and not old.stats_applied and new.status='finished') then return new; end if;
  if coalesce(new.is_bot,false) then return new; end if;

  insert into public.club_point_events(club_id,user_id,room_id,points,created_at)
  select cm.club_id,new.host_id,new.id,case when new.winner_id=new.host_id then 10 else 3 end,v_finished
  from public.club_members cm where cm.user_id=new.host_id
  on conflict(room_id,user_id) do nothing;

  if new.guest_id is not null then
    insert into public.club_point_events(club_id,user_id,room_id,points,created_at)
    select cm.club_id,new.guest_id,new.id,case when new.winner_id=new.guest_id then 10 else 3 end,v_finished
    from public.club_members cm where cm.user_id=new.guest_id
    on conflict(room_id,user_id) do nothing;
  end if;

  select t.id into v_tid
  from public.weekly_tournaments t
  where v_finished>=t.starts_at and v_finished<t.ends_at
  order by t.starts_at desc
  limit 1;

  if v_tid is not null then
    insert into public.weekly_tournament_match_events(tournament_id,user_id,room_id,points,won,created_at)
    select v_tid,new.host_id,new.id,case when new.winner_id=new.host_id then 3 else 1 end,new.winner_id=new.host_id,v_finished
    where exists(
      select 1 from public.weekly_tournament_entries e
      where e.tournament_id=v_tid and e.user_id=new.host_id and e.joined_at<=v_finished
    )
    on conflict(tournament_id,room_id,user_id) do nothing;

    if new.guest_id is not null then
      insert into public.weekly_tournament_match_events(tournament_id,user_id,room_id,points,won,created_at)
      select v_tid,new.guest_id,new.id,case when new.winner_id=new.guest_id then 3 else 1 end,new.winner_id=new.guest_id,v_finished
      where exists(
        select 1 from public.weekly_tournament_entries e
        where e.tournament_id=v_tid and e.user_id=new.guest_id and e.joined_at<=v_finished
      )
      on conflict(tournament_id,room_id,user_id) do nothing;
    end if;
  end if;
  return new;
end $$;

