-- Competitive Seasons + Persistent Achievements v1
-- Global rating remains permanent. Season rating resets to 1000 each season.
-- Bot matches are excluded. Only real PvP Son Harf and Word Arena results count.

create table if not exists public.competitive_seasons (
  id text primary key,
  name_tr text not null,
  name_en text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status text not null default 'active' check(status in ('active','ended')),
  settled_at timestamptz,
  created_at timestamptz not null default now(),
  check(ends_at>starts_at)
);

create table if not exists public.season_player_stats (
  season_id text not null references public.competitive_seasons(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  rating integer not null default 1000 check(rating>=100),
  peak_rating integer not null default 1000 check(peak_rating>=100),
  matches integer not null default 0 check(matches>=0),
  wins integer not null default 0 check(wins>=0),
  losses integer not null default 0 check(losses>=0),
  draws integer not null default 0 check(draws>=0),
  valid_words integer not null default 0 check(valid_words>=0),
  updated_at timestamptz not null default now(),
  primary key(season_id,user_id)
);
create index if not exists season_player_stats_rank_idx on public.season_player_stats(season_id,rating desc,wins desc,matches desc);
create index if not exists season_player_stats_user_idx on public.season_player_stats(user_id,season_id);

create table if not exists public.season_match_events (
  id bigint generated by default as identity primary key,
  season_id text not null references public.competitive_seasons(id) on delete cascade,
  source_type text not null check(source_type in ('classic','arena')),
  source_id uuid not null,
  user_id uuid not null references public.profiles(id) on delete cascade,
  result text not null check(result in ('win','loss','draw')),
  rating_delta integer not null,
  valid_words integer not null default 0 check(valid_words>=0),
  occurred_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique(source_type,source_id,user_id)
);
create index if not exists season_match_events_user_idx on public.season_match_events(user_id,occurred_at desc);
create index if not exists season_match_events_season_idx on public.season_match_events(season_id,occurred_at desc);

create table if not exists public.season_honors (
  season_id text not null references public.competitive_seasons(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  honor_code text not null,
  label_tr text not null,
  label_en text not null,
  final_rating integer not null,
  rank integer not null default 1,
  created_at timestamptz not null default now(),
  primary key(season_id,user_id,honor_code)
);
create index if not exists season_honors_user_idx on public.season_honors(user_id,created_at desc);

create table if not exists public.achievement_definitions (
  code text primary key,
  icon text not null,
  title_tr text not null,
  title_en text not null,
  description_tr text not null,
  description_en text not null,
  metric text not null,
  target integer not null check(target>0),
  reward_coin integer not null default 0 check(reward_coin>=0),
  sort_order integer not null,
  active boolean not null default true
);

create table if not exists public.achievement_unlocks (
  user_id uuid not null references public.profiles(id) on delete cascade,
  achievement_code text not null references public.achievement_definitions(code) on delete cascade,
  reward_coin integer not null default 0,
  unlocked_at timestamptz not null default now(),
  primary key(user_id,achievement_code)
);
create index if not exists achievement_unlocks_user_time_idx on public.achievement_unlocks(user_id,unlocked_at desc);
create index if not exists achievement_unlocks_code_idx on public.achievement_unlocks(achievement_code);

