-- Backfill launch-season results if deployment happens after eligible matches.
do $$
declare r record;
begin
  for r in
    select g.*
    from public.game_rooms g
    where g.status='finished'
      and g.stats_applied
      and not coalesce(g.is_bot,false)
      and g.guest_id is not null
      and coalesce(g.finished_at,g.created_at)>=timestamptz '2026-08-29 00:00:00+03'
      and coalesce(g.finished_at,g.created_at)<timestamptz '2026-10-01 00:00:00+03'
  loop
    perform public.record_competitive_result_v1(
      'classic',r.id,r.host_id,
      case when r.winner_id is null then 'draw' when r.winner_id=r.host_id then 'win' else 'loss' end,
      case when r.winner_id is null then 0 when r.winner_id=r.host_id then 20 else -15 end,
      (select count(*)::int from public.game_words w where w.room_id=r.id and w.player_id=r.host_id),
      coalesce(r.finished_at,r.created_at)
    );
    perform public.record_competitive_result_v1(
      'classic',r.id,r.guest_id,
      case when r.winner_id is null then 'draw' when r.winner_id=r.guest_id then 'win' else 'loss' end,
      case when r.winner_id is null then 0 when r.winner_id=r.guest_id then 20 else -15 end,
      (select count(*)::int from public.game_words w where w.room_id=r.id and w.player_id=r.guest_id),
      coalesce(r.finished_at,r.created_at)
    );
  end loop;

  for r in
    select a.*
    from public.word_arena_rooms a
    where a.status='finished'
      and a.result_applied
      and coalesce(a.finished_at,a.ends_at)>=timestamptz '2026-08-29 00:00:00+03'
      and coalesce(a.finished_at,a.ends_at)<timestamptz '2026-10-01 00:00:00+03'
  loop
    perform public.record_competitive_result_v1(
      'arena',r.id,r.host_id,
      case when r.winner_id is null then 'draw' when r.winner_id=r.host_id then 'win' else 'loss' end,
      case when r.winner_id is null then 0 when r.winner_id=r.host_id then 18 else -12 end,
      (select count(*)::int from public.word_arena_words w where w.room_id=r.id and w.user_id=r.host_id),
      coalesce(r.finished_at,r.ends_at)
    );
    perform public.record_competitive_result_v1(
      'arena',r.id,r.guest_id,
      case when r.winner_id is null then 'draw' when r.winner_id=r.guest_id then 'win' else 'loss' end,
      case when r.winner_id is null then 0 when r.winner_id=r.guest_id then 18 else -12 end,
      (select count(*)::int from public.word_arena_words w where w.room_id=r.id and w.user_id=r.guest_id),
      coalesce(r.finished_at,r.ends_at)
    );
  end loop;
end
$$;
