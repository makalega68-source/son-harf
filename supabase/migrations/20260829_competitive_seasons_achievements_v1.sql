create or replace function public.competitive_season_name_tr_v1(p_start timestamptz)
returns text
language sql
stable
set search_path=public,pg_temp
as $$
  select
    case extract(month from p_start at time zone 'Europe/Istanbul')::int
      when 1 then 'Ocak' when 2 then 'Şubat' when 3 then 'Mart' when 4 then 'Nisan'
      when 5 then 'Mayıs' when 6 then 'Haziran' when 7 then 'Temmuz' when 8 then 'Ağustos'
      when 9 then 'Eylül' when 10 then 'Ekim' when 11 then 'Kasım' else 'Aralık'
    end || ' ' ||
    extract(year from p_start at time zone 'Europe/Istanbul')::int::text ||
    ' Sezonu'
$$;

create or replace function public.ensure_competitive_season_v1(p_reference timestamptz default now())
returns text
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_id text;
  v_local timestamp;
  v_start timestamptz;
  v_end timestamptz;
begin
  perform pg_advisory_xact_lock(88112602);

  insert into public.season_honors(
    season_id,user_id,honor_code,label_tr,label_en,final_rating,rank
  )
  select
    s.id,
    winner.user_id,
    'CHAMPION',
    s.name_tr || ' Şampiyonu',
    s.name_en || ' Champion',
    winner.rating,
    1
  from public.competitive_seasons s
  cross join lateral (
    select ps.user_id,ps.rating
    from public.season_player_stats ps
    where ps.season_id=s.id and ps.matches>0
    order by ps.rating desc,ps.wins desc,ps.matches desc,ps.user_id
    limit 1
  ) winner
  where s.ends_at<=p_reference
    and s.settled_at is null
  on conflict do nothing;

  update public.competitive_seasons
  set status='ended',settled_at=coalesce(settled_at,p_reference)
  where ends_at<=p_reference and settled_at is null;

  select cs.id into v_id
  from public.competitive_seasons cs
  where p_reference>=cs.starts_at and p_reference<cs.ends_at
  order by cs.starts_at desc
  limit 1;

  if v_id is not null then return v_id; end if;

  v_local:=p_reference at time zone 'Europe/Istanbul';
  v_start:=make_timestamptz(
    extract(year from v_local)::int,
    extract(month from v_local)::int,
    1,0,0,0,'Europe/Istanbul'
  );
  v_end:=v_start+interval '1 month';
  v_id:=to_char(v_local,'YYYY-MM');

  insert into public.competitive_seasons(id,name_tr,name_en,starts_at,ends_at,status)
  values(
    v_id,
    public.competitive_season_name_tr_v1(v_start),
    to_char(v_start at time zone 'Europe/Istanbul','FMMonth YYYY') || ' Season',
    v_start,
    v_end,
    'active'
  )
  on conflict(id) do nothing;

  return v_id;
end
$$;

create or replace function public.sync_achievement_unlocks_v1(p_user_id uuid)
returns integer
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  rec record;
  v_reward int:=0;
begin
  if p_user_id is null then return 0; end if;

  for rec in
    with metrics as (
      select
        d.code,
        d.reward_coin,
        d.target,
        case d.metric
          when 'total_matches' then coalesce(p.total_matches,0)
          when 'wins' then coalesce(p.wins,0)
          when 'valid_words' then coalesce(p.valid_words,0)
          when 'best_streak' then coalesce(p.best_streak,0)
          when 'rating' then coalesce(p.rating,1000)
          when 'season_peak' then coalesce((
            select max(ps.peak_rating)
            from public.season_player_stats ps
            where ps.user_id=p_user_id
          ),1000)
          when 'season_champion' then case when exists(
            select 1 from public.season_honors h
            where h.user_id=p_user_id and h.honor_code='CHAMPION'
          ) then 1 else 0 end
          else 0
        end::int as current_value
      from public.achievement_definitions d
      join public.profiles p on p.id=p_user_id
      where d.active
    ),
    inserted as (
      insert into public.achievement_unlocks(user_id,achievement_code,reward_coin)
      select p_user_id,m.code,m.reward_coin
      from metrics m
      where m.current_value>=m.target
      on conflict do nothing
      returning achievement_code,reward_coin
    )
    select * from inserted
  loop
    v_reward:=v_reward+rec.reward_coin;
    if rec.reward_coin>0 then
      insert into public.diamond_ledger(user_id,delta,reason,item_id)
      values(p_user_id,rec.reward_coin,'achievement:'||rec.achievement_code,null);
    end if;
  end loop;

  if v_reward>0 then
    update public.profiles
    set diamonds=coalesce(diamonds,0)+v_reward,updated_at=now()
    where id=p_user_id;
  end if;

  return v_reward;
end
$$;

create or replace function public.record_competitive_result_v1(
  p_source_type text,
  p_source_id uuid,
  p_user_id uuid,
  p_result text,
  p_rating_delta integer,
  p_valid_words integer,
  p_occurred_at timestamptz
)
returns void
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_season text;
  v_inserted bigint;
  v_before int;
  v_after int;
begin
  if p_user_id is null or p_source_id is null then return; end if;
  if p_source_type not in ('classic','arena') then raise exception 'invalid_source_type'; end if;
  if p_result not in ('win','loss','draw') then raise exception 'invalid_result'; end if;

  select cs.id into v_season
  from public.competitive_seasons cs
  where p_occurred_at>=cs.starts_at and p_occurred_at<cs.ends_at
  order by cs.starts_at desc
  limit 1;

  if v_season is null then
    v_season:=public.ensure_competitive_season_v1(p_occurred_at);
  end if;

  insert into public.season_match_events(
    season_id,source_type,source_id,user_id,result,rating_delta,valid_words,occurred_at
  )
  values(
    v_season,p_source_type,p_source_id,p_user_id,p_result,p_rating_delta,
    greatest(coalesce(p_valid_words,0),0),p_occurred_at
  )
  on conflict(source_type,source_id,user_id) do nothing
  returning id into v_inserted;

  if v_inserted is null then return; end if;

  insert into public.season_player_stats(season_id,user_id)
  values(v_season,p_user_id)
  on conflict do nothing;

  select ps.rating into v_before
  from public.season_player_stats ps
  where ps.season_id=v_season and ps.user_id=p_user_id
  for update;

  v_after:=greatest(100,v_before+p_rating_delta);

  update public.season_player_stats ps
  set rating=v_after,
      peak_rating=greatest(ps.peak_rating,v_after),
      matches=ps.matches+1,
      wins=ps.wins+case when p_result='win' then 1 else 0 end,
      losses=ps.losses+case when p_result='loss' then 1 else 0 end,
      draws=ps.draws+case when p_result='draw' then 1 else 0 end,
      valid_words=ps.valid_words+greatest(coalesce(p_valid_words,0),0),
      updated_at=now()
  where ps.season_id=v_season and ps.user_id=p_user_id;

  perform public.sync_achievement_unlocks_v1(p_user_id);
end
$$;

create or replace function public.capture_classic_season_result_v1()
returns trigger
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_when timestamptz:=coalesce(new.finished_at,new.created_at,now());
  v_host_words int:=0;
  v_guest_words int:=0;
begin
  if not new.stats_applied or coalesce(old.stats_applied,false) then return new; end if;
  if new.status<>'finished' or coalesce(new.is_bot,false) or new.guest_id is null then return new; end if;

  select count(*)::int into v_host_words from public.game_words where room_id=new.id and player_id=new.host_id;
  select count(*)::int into v_guest_words from public.game_words where room_id=new.id and player_id=new.guest_id;

  perform public.record_competitive_result_v1(
    'classic',new.id,new.host_id,
    case when new.winner_id is null then 'draw' when new.winner_id=new.host_id then 'win' else 'loss' end,
    case when new.winner_id is null then 0 when new.winner_id=new.host_id then 20 else -15 end,
    v_host_words,v_when
  );
  perform public.record_competitive_result_v1(
    'classic',new.id,new.guest_id,
    case when new.winner_id is null then 'draw' when new.winner_id=new.guest_id then 'win' else 'loss' end,
    case when new.winner_id is null then 0 when new.winner_id=new.guest_id then 20 else -15 end,
    v_guest_words,v_when
  );
  return new;
end
$$;

drop trigger if exists trg_capture_classic_season_result_v1 on public.game_rooms;
create trigger trg_capture_classic_season_result_v1
after update of stats_applied on public.game_rooms
for each row
when (new.stats_applied=true and old.stats_applied is distinct from true)
execute function public.capture_classic_season_result_v1();

