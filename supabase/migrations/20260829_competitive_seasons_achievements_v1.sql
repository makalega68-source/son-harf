create or replace function public.get_competitive_season_v1()
returns table(
  season_id text,
  name_tr text,
  name_en text,
  starts_at timestamptz,
  ends_at timestamptz,
  rating integer,
  peak_rating integer,
  league_name text,
  season_rank bigint,
  player_count bigint,
  matches integer,
  wins integer,
  losses integer,
  draws integer,
  valid_words integer,
  next_rating integer,
  points_to_next integer,
  honor_count bigint,
  latest_honor_tr text,
  latest_honor_en text
)
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
  v_sid text;
begin
  if v_uid is null then raise exception 'not_authenticated'; end if;
  v_sid:=public.ensure_competitive_season_v1(now());

  insert into public.season_player_stats(season_id,user_id)
  values(v_sid,v_uid)
  on conflict do nothing;

  perform public.sync_achievement_unlocks_v1(v_uid);

  return query
  with ranked as (
    select
      ps.user_id,
      rank() over(order by ps.rating desc,ps.wins desc,ps.matches desc,ps.user_id) rnk,
      count(*) over() cnt
    from public.season_player_stats ps
    where ps.season_id=v_sid and ps.matches>0
  ),
  mine as (
    select ps2.*
    from public.season_player_stats ps2
    where ps2.season_id=v_sid and ps2.user_id=v_uid
  )
  select
    s.id,
    s.name_tr,
    s.name_en,
    s.starts_at,
    s.ends_at,
    m.rating,
    m.peak_rating,
    public.league_for_rating_v1(m.rating),
    coalesce(r.rnk,0)::bigint,
    coalesce((select max(r2.cnt) from ranked r2),0)::bigint,
    m.matches,
    m.wins,
    m.losses,
    m.draws,
    m.valid_words,
    case
      when m.rating<1100 then 1100
      when m.rating<1250 then 1250
      when m.rating<1400 then 1400
      when m.rating<1600 then 1600
      when m.rating<1800 then 1800
      else null
    end,
    case
      when m.rating<1100 then 1100-m.rating
      when m.rating<1250 then 1250-m.rating
      when m.rating<1400 then 1400-m.rating
      when m.rating<1600 then 1600-m.rating
      when m.rating<1800 then 1800-m.rating
      else 0
    end,
    (select count(*) from public.season_honors h where h.user_id=v_uid),
    (select h.label_tr from public.season_honors h where h.user_id=v_uid order by h.created_at desc limit 1),
    (select h.label_en from public.season_honors h where h.user_id=v_uid order by h.created_at desc limit 1)
  from public.competitive_seasons s
  join mine m on true
  left join ranked r on r.user_id=v_uid
  where s.id=v_sid;
end
$$;

create or replace function public.get_season_leaderboard_v1(p_limit integer default 50)
returns table(
  user_id uuid,
  display_name text,
  rating integer,
  peak_rating integer,
  league_name text,
  matches integer,
  wins integer,
  losses integer,
  draws integer,
  win_rate numeric,
  rank_no bigint
)
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
  v_sid text;
begin
  if v_uid is null then raise exception 'not_authenticated'; end if;
  v_sid:=public.ensure_competitive_season_v1(now());

  return query
  select
    ps.user_id,
    p.display_name,
    ps.rating,
    ps.peak_rating,
    public.league_for_rating_v1(ps.rating),
    ps.matches,
    ps.wins,
    ps.losses,
    ps.draws,
    case when ps.matches=0 then 0 else round(ps.wins*100.0/ps.matches,1) end,
    rank() over(order by ps.rating desc,ps.wins desc,ps.matches desc,ps.user_id)
  from public.season_player_stats ps
  join public.profiles p on p.id=ps.user_id
  where ps.season_id=v_sid and ps.matches>0
  order by ps.rating desc,ps.wins desc,ps.matches desc,ps.user_id
  limit greatest(1,least(coalesce(p_limit,50),100));
end
$$;

create or replace function public.get_achievements_v1()
returns table(
  code text,
  icon text,
  title_tr text,
  title_en text,
  description_tr text,
  description_en text,
  current_value integer,
  target integer,
  reward_coin integer,
  unlocked boolean,
  unlocked_at timestamptz
)
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
  v_uid uuid:=auth.uid();
begin
  if v_uid is null then raise exception 'not_authenticated'; end if;
  perform public.ensure_competitive_season_v1(now());
  perform public.sync_achievement_unlocks_v1(v_uid);

  return query
  select
    d.code,
    d.icon,
    d.title_tr,
    d.title_en,
    d.description_tr,
    d.description_en,
    case d.metric
      when 'total_matches' then coalesce(p.total_matches,0)
      when 'wins' then coalesce(p.wins,0)
      when 'valid_words' then coalesce(p.valid_words,0)
      when 'best_streak' then coalesce(p.best_streak,0)
      when 'rating' then coalesce(p.rating,1000)
      when 'season_peak' then coalesce((select max(ps.peak_rating) from public.season_player_stats ps where ps.user_id=v_uid),1000)
      when 'season_champion' then case when exists(
        select 1 from public.season_honors h where h.user_id=v_uid and h.honor_code='CHAMPION'
      ) then 1 else 0 end
      else 0
    end::int,
    d.target,
    d.reward_coin,
    u.achievement_code is not null,
    u.unlocked_at
  from public.achievement_definitions d
  join public.profiles p on p.id=v_uid
  left join public.achievement_unlocks u on u.user_id=v_uid and u.achievement_code=d.code
  where d.active
  order by d.sort_order,d.code;
end
$$;

