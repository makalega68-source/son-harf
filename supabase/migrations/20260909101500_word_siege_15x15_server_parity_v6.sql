-- Fail the migration rather than committing a mixed 9x9/15x15 state.
do $final_parity$
declare
  v_bad_games integer;
  v_board_cells integer;
begin
  select jsonb_array_length(private.word_siege_new_board_v1()) into v_board_cells;
  if v_board_cells <> 225 then
    raise exception 'word_siege_new_board_not_225';
  end if;

  select count(*) into v_bad_games
  from public.word_siege_games
  where jsonb_typeof(board) <> 'array'
     or jsonb_array_length(board) <> 225;
  if v_bad_games <> 0 then
    raise exception 'word_siege_non_225_games_remaining:%', v_bad_games;
  end if;
end
$final_parity$;

