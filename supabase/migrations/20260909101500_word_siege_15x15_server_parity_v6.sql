  add constraint word_siege_games_player_one_area_v6_check
    check (player_one_area between 0 and 225),
  add constraint word_siege_games_player_two_area_v6_check
    check (player_two_area between 0 and 225),
  add constraint word_siege_games_board_v6_check
    check (jsonb_typeof(board) = 'array' and jsonb_array_length(board) = 225);

create or replace function private.word_siege_collect_cells_v1(
  p_board jsonb,
  p_placements jsonb,
  p_rack text,
  p_anchor integer,
  p_delta integer
)
returns integer[]
language plpgsql
stable
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  v_start integer := p_anchor;
  v_current integer;
  v_next integer;
  v_cells integer[] := array[]::integer[];
begin
  if p_delta not in (1, 15) or p_anchor not between 0 and 224 then
    return v_cells;
  end if;
  if private.word_siege_letter_at_v1(p_board, p_placements, p_rack, p_anchor) is null then
    return v_cells;
  end if;

  loop
    v_next := v_start - p_delta;
    exit when v_next < 0;
    exit when p_delta = 1 and (v_next / 15) <> (v_start / 15);
    exit when private.word_siege_letter_at_v1(p_board, p_placements, p_rack, v_next) is null;
    v_start := v_next;
  end loop;

  v_current := v_start;
  loop
    exit when v_current > 224;
    exit when p_delta = 1 and (v_current / 15) <> (v_start / 15);
    exit when private.word_siege_letter_at_v1(p_board, p_placements, p_rack, v_current) is null;
    v_cells := array_append(v_cells, v_current);
    v_next := v_current + p_delta;
    exit when v_next > 224;
    exit when p_delta = 1 and (v_next / 15) <> (v_current / 15);
    v_current := v_next;
  end loop;

  return v_cells;
end
$$;

create or replace function private.word_siege_area_delta_v1(
  p_before_board jsonb,
  p_after_board jsonb,
  p_owner integer
)
returns table(neutral_captured integer, opponent_captured integer, area_score integer)
language sql
immutable
set search_path = pg_catalog, public, private, pg_temp
as $$
  with ownership as (
    select i,
      coalesce((p_before_board -> i ->> 'owner')::integer, 0) as before_owner,
      coalesce((p_after_board -> i ->> 'owner')::integer, 0) as after_owner
    from generate_series(0, 224) i
  ), counts as (
    select
      count(*) filter (where before_owner = 0 and after_owner = p_owner)::integer as neutral_count,
      count(*) filter (
        where before_owner not in (0, p_owner) and after_owner = p_owner
      )::integer as opponent_count
    from ownership
  )
  select neutral_count, opponent_count, (neutral_count + opponent_count) * 2
  from counts
$$;

-- Preserve all newer submit behavior and patch only its board-geometry contract.
do $submit_geometry$
declare
  v_def text;
  v_src text;
begin
  select pg_get_functiondef(
    'private.submit_word_siege_move_v1(uuid,jsonb,boolean)'::regprocedure
  ) into v_def;
  if v_def is null then
    raise exception 'word_siege_submit_function_missing';
  end if;

  v_def := replace(v_def, 'x not between 0 and 80', 'x not between 0 and 224');
  v_def := replace(v_def, 'x / 9 <> v_anchor / 9', 'x / 15 <> v_anchor / 15');
  v_def := replace(v_def, 'x % 9 <> v_anchor % 9', 'x % 15 <> v_anchor % 15');
  v_def := replace(v_def, 'case when p_horizontal then 1 else 9 end', 'case when p_horizontal then 1 else 15 end');
  v_def := replace(v_def, 'case when p_horizontal then 9 else 1 end', 'case when p_horizontal then 15 else 1 end');
  v_def := replace(v_def, '40 = any(v_indices)', '112 = any(v_indices)');
  execute v_def;

  select p.prosrc into v_src
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'private'
    and p.proname = 'submit_word_siege_move_v1'
    and p.oid = 'private.submit_word_siege_move_v1(uuid,jsonb,boolean)'::regprocedure;

  if v_src not like '%x not between 0 and 224%'
     or v_src not like '%x / 15 <> v_anchor / 15%'
     or v_src not like '%x % 15 <> v_anchor % 15%'
     or v_src not like '%112 = any(v_indices)%'
     or v_src like '%x not between 0 and 80%'
     or v_src like '%x / 9 <> v_anchor / 9%'
     or v_src like '%x % 9 <> v_anchor % 9%'
     or v_src like '%40 = any(v_indices)%' then
    raise exception 'word_siege_submit_geometry_patch_failed';
  end if;
end
$submit_geometry$;

