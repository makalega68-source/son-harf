-- Word Siege v6: recover production drift and enforce canonical 15x15 server geometry.
-- This migration is intentionally forward-only and idempotent:
-- - fresh databases may already have the v4 15x15 helpers;
-- - drifted production databases may still have 9x9 helpers/validators.
-- Preserve the newer shared dictionary validator and v5 final-score semantics.

-- Serialize board/move conversion against live game writes.
lock table public.word_siege_games in share row exclusive mode;
lock table public.word_siege_moves in share row exclusive mode;

create or replace function private.word_siege_new_board_v1()
returns jsonb
language sql
immutable
set search_path = pg_catalog, public, private, pg_temp
as $$
  select jsonb_agg(
    jsonb_build_object(
      'letter', null,
      'owner', 0,
      'bonus', case
        when i in (0,7,14,105,119,210,217,224) then '3K'
        when i in (20,24,76,80,84,88,136,140,144,148,200,204) then '3H'
        when i in (16,28,32,42,48,56,64,70,112,154,160,168,176,182,192,196,208) then '2K'
        when i in (3,11,36,38,45,52,59,92,96,98,102,108,116,122,126,128,132,165,172,179,186,188,213,221) then '2H'
        else null
      end,
      'bonus_used', false
    ) order by i
  )
  from generate_series(0, 224) i
$$;

-- Remap legacy 9x9 move coordinates into the centered 9x9 region of the 15x15 board.
update public.word_siege_moves m
set placed_tiles = (
  select coalesce(
    jsonb_agg(
      tile || jsonb_build_object(
        'index', ((((tile ->> 'index')::integer / 9) + 3) * 15)
                 + (((tile ->> 'index')::integer % 9) + 3)
      ) order by ordinality
    ),
    '[]'::jsonb
  )
  from jsonb_array_elements(m.placed_tiles) with ordinality as t(tile, ordinality)
)
where exists (
  select 1
  from public.word_siege_games g
  where g.id = m.game_id
    and jsonb_typeof(g.board) = 'array'
    and jsonb_array_length(g.board) = 81
);

-- Preserve legacy letters, ownership and used-bonus state while centering the old board.
update public.word_siege_games g
set board = (
  with fresh as (select private.word_siege_new_board_v1() as board)
  select jsonb_agg(
    case
      when (i / 15) between 3 and 11 and (i % 15) between 3 and 11 then
        (fresh.board -> i) || jsonb_build_object(
          'letter', g.board -> ((((i / 15) - 3) * 9) + ((i % 15) - 3)) -> 'letter',
          'owner', coalesce(
            g.board -> ((((i / 15) - 3) * 9) + ((i % 15) - 3)) -> 'owner',
            '0'::jsonb
          ),
          'bonus_used', coalesce(
            g.board -> ((((i / 15) - 3) * 9) + ((i % 15) - 3)) -> 'bonus_used',
            'false'::jsonb
          )
        )
      else fresh.board -> i
    end
    order by i
  )
  from fresh, generate_series(0, 224) i
)
where jsonb_typeof(g.board) = 'array'
  and jsonb_array_length(g.board) = 81;

-- Remove any legacy 81-cell checks without depending on autogenerated constraint names.
do $constraints$
declare
  c record;
begin
  for c in
    select conname, pg_get_constraintdef(oid) as definition
    from pg_constraint
    where conrelid = 'public.word_siege_games'::regclass
      and contype = 'c'
  loop
    if c.definition like '%player_one_area%81%'
       or c.definition like '%player_two_area%81%'
       or c.definition like '%jsonb_array_length(board)%81%' then
      execute format('alter table public.word_siege_games drop constraint %I', c.conname);
    end if;
  end loop;
end
$constraints$;

alter table public.word_siege_games
