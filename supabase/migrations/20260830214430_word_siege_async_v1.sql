-- Kelime Kusatmasi v1: unlimited-time asynchronous 1v1 territory word game.
-- The server owns the bag, racks, board validation, bonuses, scoring and territory.

create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table if not exists public.word_siege_games (
  id uuid primary key default gen_random_uuid(),
  player_one_id uuid not null references public.profiles(id) on delete cascade,
  player_two_id uuid references public.profiles(id) on delete set null,
  status text not null default 'waiting'
    check (status in ('waiting', 'playing', 'finished', 'cancelled')),
  language text not null default 'tr' check (language in ('tr', 'en')),
  current_player_id uuid references public.profiles(id) on delete set null,
  winner_id uuid references public.profiles(id) on delete set null,
  board jsonb not null,
  bag text not null,
  player_one_rack text not null,
  player_two_rack text,
  player_one_word_score integer not null default 0 check (player_one_word_score >= 0),
  player_two_word_score integer not null default 0 check (player_two_word_score >= 0),
  player_one_area integer not null default 0 check (player_one_area between 0 and 81),
  player_two_area integer not null default 0 check (player_two_area between 0 and 81),
  consecutive_passes integer not null default 0 check (consecutive_passes between 0 and 2),
  move_count integer not null default 0 check (move_count >= 0),
  last_action text,
  last_action_player_id uuid references public.profiles(id) on delete set null,
  last_move_at timestamptz,
  finish_reason text,
  result_applied boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  finished_at timestamptz,
  check (player_two_id is null or player_two_id <> player_one_id),
  check (jsonb_typeof(board) = 'array' and jsonb_array_length(board) = 81)
);

create table if not exists public.word_siege_moves (
  id bigint generated by default as identity primary key,
  game_id uuid not null references public.word_siege_games(id) on delete cascade,
  player_id uuid not null references public.profiles(id) on delete cascade,
  primary_word text not null,
  formed_words text[] not null,
  placed_tiles jsonb not null,
  word_score integer not null check (word_score >= 0),
  captured_cells integer not null default 0 check (captured_cells >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.word_siege_messages (
  id bigint generated by default as identity primary key,
  game_id uuid not null references public.word_siege_games(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 300),
  created_at timestamptz not null default now()
);

create index if not exists word_siege_games_player_one_updated_idx
  on public.word_siege_games(player_one_id, updated_at desc);
create index if not exists word_siege_games_player_two_updated_idx
  on public.word_siege_games(player_two_id, updated_at desc)
  where player_two_id is not null;
create index if not exists word_siege_games_waiting_idx
  on public.word_siege_games(language, created_at)
  where status = 'waiting';
create index if not exists word_siege_games_turn_idx
  on public.word_siege_games(current_player_id, updated_at desc)
  where status = 'playing';
create index if not exists word_siege_moves_game_created_idx
  on public.word_siege_moves(game_id, created_at, id);
create index if not exists word_siege_moves_player_idx
  on public.word_siege_moves(player_id, created_at desc);
create index if not exists word_siege_messages_game_created_idx
  on public.word_siege_messages(game_id, created_at, id);
create index if not exists word_siege_messages_sender_idx
  on public.word_siege_messages(sender_id, created_at desc);

alter table public.word_siege_games enable row level security;
alter table public.word_siege_moves enable row level security;
alter table public.word_siege_messages enable row level security;

revoke all on public.word_siege_games from anon, authenticated;
revoke all on public.word_siege_moves from anon, authenticated;
revoke all on public.word_siege_messages from anon, authenticated;

