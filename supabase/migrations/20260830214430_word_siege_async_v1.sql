drop policy if exists word_siege_messages_sender_insert on public.word_siege_messages;
create policy word_siege_messages_sender_insert
on public.word_siege_messages
for insert
to authenticated
with check (
  sender_id = (select auth.uid())
  and char_length(btrim(body)) between 1 and 300
  and exists (
    select 1
    from public.word_siege_games g
    where g.id = word_siege_messages.game_id
      and g.status in ('playing', 'finished')
      and (select auth.uid()) in (g.player_one_id, g.player_two_id)
      and not exists (
        select 1
        from public.user_blocks b
        where (b.blocker_id = g.player_one_id and b.blocked_id = g.player_two_id)
           or (b.blocker_id = g.player_two_id and b.blocked_id = g.player_one_id)
      )
  )
  and exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and coalesce(p.allow_match_chat, true)
      and (p.chat_suspended_until is null or p.chat_suspended_until <= now())
  )
);

