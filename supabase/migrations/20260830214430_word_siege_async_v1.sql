create or replace function private.word_siege_new_board_v1()
returns jsonb
language sql
immutable
set search_path = pg_catalog, public, private, pg_temp
as $$
  select jsonb_agg(
    jsonb_build_object(
      'letter', null,
      'owner', 0,
      'bonus', case
        when i in (0, 8, 72, 80) then '3K'
        when i in (4, 36, 44, 76) then '3H'
        when i in (10, 16, 64, 70) then '2K'
        when i in (20, 24, 56, 60) then '2H'
        when i = 40 then '2K'
        else null
      end,
      'bonus_used', false
    )
    order by i
  )
  from generate_series(0, 80) i
$$;

create or replace function private.word_siege_shuffle_text_v1(p_text text)
returns text
language sql
volatile
set search_path = pg_catalog, public, private, pg_temp
as $$
  select coalesce(string_agg(ch, '' order by random()), '')
  from regexp_split_to_table(coalesce(p_text, ''), '') ch
  where ch <> ''
$$;

create or replace function private.word_siege_new_bag_v1(p_language text)
returns text
language plpgsql
volatile
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  v_letters text;
begin
  if lower(coalesce(p_language, 'tr')) = 'en' then
    v_letters := repeat('E', 12) || repeat('A', 9) || repeat('I', 9) || repeat('O', 8) ||
      repeat('N', 6) || repeat('R', 6) || repeat('T', 6) || repeat('L', 4) || repeat('S', 4) ||
      repeat('U', 4) || repeat('D', 4) || repeat('G', 3) || repeat('B', 2) || repeat('C', 2) ||
      repeat('M', 2) || repeat('P', 2) || repeat('F', 2) || repeat('H', 2) || repeat('V', 2) ||
      repeat('W', 2) || repeat('Y', 2) || 'KJXQZ';
  else
    v_letters := repeat('A', 12) || repeat('B', 2) || repeat('C', 2) || repeat('Ç', 2) ||
      repeat('D', 2) || repeat('E', 8) || 'F' || 'G' || 'Ğ' || 'H' || repeat('I', 4) ||
      repeat('İ', 7) || 'J' || repeat('K', 7) || repeat('L', 7) || repeat('M', 4) ||
      repeat('N', 5) || repeat('O', 3) || 'Ö' || 'P' || repeat('R', 6) || repeat('S', 3) ||
      repeat('Ş', 2) || repeat('T', 5) || repeat('U', 3) || repeat('Ü', 2) || 'V' ||
      repeat('Y', 2) || repeat('Z', 2);
  end if;
  return private.word_siege_shuffle_text_v1(v_letters);
end
$$;

create or replace function private.word_siege_letter_value_v1(p_letter text)
returns integer
language sql
immutable
set search_path = pg_catalog, public, private, pg_temp
as $$
  select case coalesce(p_letter, '')
    when 'A' then 1 when 'B' then 3 when 'C' then 4 when 'Ç' then 4
    when 'D' then 3 when 'E' then 1 when 'F' then 7 when 'G' then 5
    when 'Ğ' then 8 when 'H' then 5 when 'I' then 2 when 'İ' then 1
    when 'J' then 10 when 'K' then 1 when 'L' then 1 when 'M' then 2
    when 'N' then 1 when 'O' then 2 when 'Ö' then 7 when 'P' then 5
    when 'R' then 1 when 'S' then 2 when 'Ş' then 4 when 'T' then 1
    when 'U' then 2 when 'Ü' then 3 when 'V' then 7 when 'Y' then 3
    when 'Z' then 4
    else 1
  end
$$;

create or replace function private.word_siege_letter_at_v1(
  p_board jsonb,
  p_placements jsonb,
  p_rack text,
  p_index integer
)
returns text
language plpgsql
stable
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  v_letter text;
begin
  select substring(p_rack from ((e ->> 'rack_index')::integer + 1) for 1)
  into v_letter
  from jsonb_array_elements(p_placements) e
  where (e ->> 'index')::integer = p_index
  limit 1;

  if v_letter is not null then return v_letter; end if;
  return nullif(p_board -> p_index ->> 'letter', '');
end
$$;

create or replace function private.word_siege_collect_cells_v1(
  p_board jsonb,
  p_placements jsonb,
  p_rack text,
  p_anchor integer,
  p_delta integer
)
returns integer[]
language plpgsql
stable
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  v_start integer := p_anchor;
  v_current integer;
  v_next integer;
  v_cells integer[] := array[]::integer[];
begin
  if p_delta not in (1, 9) or p_anchor not between 0 and 80 then
    return v_cells;
  end if;
  if private.word_siege_letter_at_v1(p_board, p_placements, p_rack, p_anchor) is null then
    return v_cells;
  end if;

  loop
    v_next := v_start - p_delta;
    exit when v_next < 0;
    exit when p_delta = 1 and (v_next / 9) <> (v_start / 9);
    exit when private.word_siege_letter_at_v1(p_board, p_placements, p_rack, v_next) is null;
    v_start := v_next;
  end loop;

  v_current := v_start;
  loop
    exit when v_current > 80;
    exit when p_delta = 1 and (v_current / 9) <> (v_start / 9);
    exit when private.word_siege_letter_at_v1(p_board, p_placements, p_rack, v_current) is null;
    v_cells := array_append(v_cells, v_current);
    v_next := v_current + p_delta;
    exit when v_next > 80;
    exit when p_delta = 1 and (v_next / 9) <> (v_current / 9);
    v_current := v_next;
  end loop;
  return v_cells;
end
$$;

create or replace function private.word_siege_word_from_cells_v1(
  p_board jsonb,
  p_placements jsonb,
  p_rack text,
  p_cells integer[]
)
returns text
language plpgsql
stable
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  v_index integer;
  v_word text := '';
begin
  foreach v_index in array p_cells loop
    v_word := v_word || coalesce(
      private.word_siege_letter_at_v1(p_board, p_placements, p_rack, v_index),
      ''
    );
  end loop;
  return v_word;
end
$$;

create or replace function private.word_siege_word_allowed_v1(p_word text, p_language text)
returns boolean
language plpgsql
stable
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  v_language text := case when lower(coalesce(p_language, 'tr')) = 'en' then 'en' else 'tr' end;
  v_normalized text;
begin
  v_normalized := public.normalize_game_word(v_language, trim(coalesce(p_word, '')));
  if char_length(v_normalized) not between 2 and 9 then return false; end if;
  if v_language = 'tr' and (left(v_normalized, 1) = 'ğ' or right(v_normalized, 1) = 'ğ') then
    return false;
  end if;
  return exists (
    select 1
    from public.dictionary_words d
    where d.language = v_language
      and d.active
      and d.normalized_word = v_normalized
  );
end
$$;

create or replace function private.word_siege_score_word_v1(
  p_board jsonb,
  p_placements jsonb,
  p_rack text,
  p_cells integer[]
)
returns integer
language plpgsql
stable
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  v_index integer;
  v_cell jsonb;
  v_letter text;
  v_bonus text;
  v_letter_score integer;
  v_word_multiplier integer := 1;
  v_total integer := 0;
  v_is_new boolean;
begin
  foreach v_index in array p_cells loop
    v_cell := p_board -> v_index;
    v_letter := private.word_siege_letter_at_v1(p_board, p_placements, p_rack, v_index);
    v_letter_score := private.word_siege_letter_value_v1(v_letter);
    v_is_new := (v_cell ->> 'letter') is null;
    v_bonus := case
      when v_is_new and not coalesce((v_cell ->> 'bonus_used')::boolean, false)
        then v_cell ->> 'bonus'
      else null
    end;
    if v_bonus = '2H' then v_letter_score := v_letter_score * 2; end if;
    if v_bonus = '3H' then v_letter_score := v_letter_score * 3; end if;
    if v_bonus = '2K' then v_word_multiplier := v_word_multiplier * 2; end if;
    if v_bonus = '3K' then v_word_multiplier := v_word_multiplier * 3; end if;
    v_total := v_total + v_letter_score;
  end loop;
  return v_total * v_word_multiplier;
end
$$;

create or replace function private.finish_word_siege_game_v1(
  p_game_id uuid,
  p_reason text,
  p_forfeit_winner uuid default null
)
returns public.word_siege_games
language plpgsql
security definer
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  r public.word_siege_games;
  v_uid uuid := auth.uid();
  v_winner uuid;
  v_one_total integer;
  v_two_total integer;
begin
  if v_uid is null then raise exception 'word_siege_unauthorized'; end if;
  select * into r
  from public.word_siege_games
  where id = p_game_id
  for update;
  if r.id is null then raise exception 'word_siege_not_found'; end if;
  if v_uid not in (r.player_one_id, r.player_two_id) then raise exception 'word_siege_not_participant'; end if;
  if r.status = 'finished' then return r; end if;
  if r.status <> 'playing' then raise exception 'word_siege_not_playing'; end if;

  v_one_total := r.player_one_word_score + r.player_one_area;
  v_two_total := r.player_two_word_score + r.player_two_area;
  if p_forfeit_winner is not null then
    if p_forfeit_winner not in (r.player_one_id, r.player_two_id) then
      raise exception 'word_siege_invalid_winner';
    end if;
    v_winner := p_forfeit_winner;
  else
    v_winner := case
      when v_one_total > v_two_total then r.player_one_id
      when v_two_total > v_one_total then r.player_two_id
      when r.player_one_area > r.player_two_area then r.player_one_id
      when r.player_two_area > r.player_one_area then r.player_two_id
      else null
    end;
  end if;

  update public.word_siege_games
  set status = 'finished',
      current_player_id = null,
      winner_id = v_winner,
      finish_reason = left(coalesce(p_reason, 'completed'), 40),
      result_applied = true,
      finished_at = now(),
      updated_at = now()
  where id = r.id
  returning * into r;
  return r;
end
$$;

create or replace function private.find_or_create_word_siege_game_v1(p_language text default 'tr')
returns public.word_siege_games
language plpgsql
security definer
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  v_uid uuid := auth.uid();
  v_language text := case when lower(coalesce(p_language, 'tr')) = 'en' then 'en' else 'tr' end;
  v_bag text;
  v_rack text;
  v_active_count integer;
  r public.word_siege_games;
begin
  if v_uid is null then raise exception 'word_siege_unauthorized'; end if;
  if not exists (select 1 from public.profiles p where p.id = v_uid) then
    raise exception 'word_siege_profile_required';
  end if;
  perform pg_advisory_xact_lock(hashtextextended('word_siege:' || v_language, 0));

  select count(*)::integer into v_active_count
  from public.word_siege_games g
  where g.status in ('waiting', 'playing')
    and v_uid in (g.player_one_id, g.player_two_id);
  if v_active_count >= 10 then raise exception 'word_siege_active_limit'; end if;

  select * into r
  from public.word_siege_games g
  where g.status = 'waiting'
    and g.player_one_id = v_uid
    and g.language = v_language
  order by g.created_at
  limit 1;
  if r.id is not null then return r; end if;

  select * into r
  from public.word_siege_games g
  where g.status = 'waiting'
    and g.language = v_language
    and g.player_one_id <> v_uid
    and not exists (
      select 1
      from public.user_blocks b
      where (b.blocker_id = v_uid and b.blocked_id = g.player_one_id)
         or (b.blocker_id = g.player_one_id and b.blocked_id = v_uid)
    )
  order by g.created_at
  for update skip locked
  limit 1;

  if r.id is not null then
    update public.word_siege_games
    set player_two_id = v_uid,
        player_two_rack = substring(r.bag from 1 for 7),
        bag = substring(r.bag from 8),
        status = 'playing',
        current_player_id = r.player_one_id,
        last_action = 'game_started',
        updated_at = now()
    where id = r.id
    returning * into r;
    return r;
  end if;

  v_bag := private.word_siege_new_bag_v1(v_language);
  v_rack := substring(v_bag from 1 for 7);
  v_bag := substring(v_bag from 8);
  insert into public.word_siege_games(
    player_one_id, language, board, bag, player_one_rack, last_action
  ) values (
    v_uid, v_language, private.word_siege_new_board_v1(), v_bag, v_rack, 'waiting_for_opponent'
  )
  returning * into r;
  return r;
end
$$;

create or replace function private.cancel_word_siege_waiting_v1(p_game_id uuid)
returns public.word_siege_games
language plpgsql
security definer
set search_path = pg_catalog, public, private, pg_temp
as $$
declare
  r public.word_siege_games;
  v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'word_siege_unauthorized'; end if;
